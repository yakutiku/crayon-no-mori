// i 枚目の線画（<svg>）。区画は data-region="0.." を持つ <path>
export function coloringSheet(i) {
  const sh = SHEETS[((i % SHEETS.length) + SHEETS.length) % SHEETS.length];
  const g = svg(300, 300, { 'data-sheet': sh.key });
  sh.regions.forEach((d, k) => {
    g.append(s('path', { d, fill: P.white, 'data-region': k, style: 'cursor:pointer', ...line(6) }));
  });
  sh.marks.forEach((m) => {
    g.append(s('path', { d: m.d, fill: m.dot ? P.brown : 'none', ...line(m.dot ? 2 : 4.5), 'pointer-events': 'none' }));
  });
  g.setAttribute('filter', CRAYON_LITE);
  return g;
}
